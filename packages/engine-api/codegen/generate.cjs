function tsDoc(doc, indent = '') {
  if (!doc || doc.length === 0) return '';
  if (doc.length === 1) return `${indent}/** ${doc[0]} */\n`;
  return `${indent}/**\n${doc.map((d) => `${indent} * ${d}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

function tsScalar(model, n) {
  switch (n) {
    case 'bool': return 'boolean';
    case 'string': return 'string';
    case 'bytes': return 'Uint8Array';
    case 'i32': case 'u32': case 'i64': case 'u64': case 'f32': case 'f64': return 'number';
    default: return n;
  }
}

function tsTypeRef(model, t) {
  const n = SCALARS.has(t.name) ? tsScalar(model, t.name) : t.name;
  return t.list ? `${n}[]` : n;
}

function genTsTypes(model) {
  let out = `/* eslint-disable */\n// ${HEADER_NOTE}\n\n`;
  out += `/** Protocol version this file was generated for. */\n`;
  out += `export const PROTOCOL_VERSION = { major: ${model.version.major}, minor: ${model.version.minor} } as const;\n\n`;
  for (const o of model.order) {
    if (o.kind === 'enum') {
      const e = model.enums.get(o.name);
      out += tsDoc(e.doc);
      out += `export type ${e.name} =\n${e.members.map((m) => `  | '${m.name}'`).join('\n')};\n`;
      out += `export const ${e.name}Values = [${e.members.map((m) => `'${m.name}'`).join(', ')}] as const;\n\n`;
    }
  }
  for (const a of model.aliases.values()) {
    out += tsDoc(a.doc);
    out += `export type ${a.name} = ${tsScalar(model, a.target)};\n\n`;
  }
  for (const o of model.order) {
    if (o.kind === 'struct') {
      const s = model.structs.get(o.name);
      out += tsDoc(s.doc);
      if (s.fields.length === 0) { out += `export interface ${s.name} {}\n\n`; continue; }
      out += `export interface ${s.name} {\n`;
      for (const f of s.fields) {
        out += tsDoc(f.doc, '  ');
        out += `  ${f.name}${f.optional ? '?' : ''}: ${tsTypeRef(model, f.type)};\n`;
      }
      out += `}\n\n`;
    } else if (o.kind === 'union') {
      const u = model.unions.get(o.name);
      out += tsDoc(u.doc);
      const arms = u.variants.map((v) => {
        if (u.flat) return `  | ({ type: '${v.name}' } & ${v.type})`;
        if (v.type === 'void') return `  | { kind: '${v.name}' }`;
        return `  | { kind: '${v.name}'; value: ${SCALARS.has(v.type) ? tsScalar(model, v.type) : v.type} }`;
      });
      out += `export type ${u.name} =\n${arms.join('\n')};\n`;
      out += `export type ${u.name}${u.flat ? 'Type' : 'Kind'} = ${u.name}['${u.flat ? 'type' : 'kind'}'];\n\n`;
    }
  }
  // Convenience maps: command → args / result types.
  out += `/** Arguments of each command, by name. */\nexport interface CommandArgs {\n${model.commands.map((c) => `  ${c.name}: ${c.typeName};`).join('\n')}\n}\n\n`;
  out += `/** Result of each command, by name. */\nexport interface CommandResults {\n${model.commands.map((c) => `  ${c.name}: ${c.result ?? 'Empty'};`).join('\n')}\n}\n\n`;
  out += `/** Arguments of each query, by name. */\nexport interface QueryArgs {\n${model.queries.map((c) => `  ${c.name}: ${c.typeName};`).join('\n')}\n}\n\n`;
  out += `/** Result of each query, by name. */\nexport interface QueryResults {\n${model.queries.map((c) => `  ${c.name}: ${c.result};`).join('\n')}\n}\n\n`;
  out += `/** Payload of each event, by name. */\nexport interface EventPayloads {\n${model.events.map((c) => `  ${c.name}: ${c.typeName};`).join('\n')}\n}\n`;
  return out;
}

/**
 * The TypeScript codec. `opts` exists for the standalone family modules
 * (genTsFamilyModule): a different wire-runtime import, types declared in the
 * same file (prefix ''), and no EngineMessage helpers.
 */
function genTsCodec(model, opts = {}) {
  const { wireImport = '../wire', typesImport = './types', envelope = true, header = true } = opts;
  const TP = typesImport ? 'T.' : '';
  const L = [];
  if (header) {
    L.push('/* eslint-disable */');
    L.push(`// ${HEADER_NOTE}`);
    L.push('');
  }
  L.push(`import { Reader, Writer, DecodeError } from '${wireImport}';`);
  const typeNames = messageTypes(model);
  if (typesImport) L.push(`import type * as T from '${typesImport}';`);
  L.push('');

  // Enum tables.
  for (const e of model.enums.values()) {
    L.push(`const ${e.name}_TO_NUM: Record<string, number> = { ${e.members.map((m) => `'${m.name}': ${m.num}`).join(', ')} };`);
    const maxNum = Math.max(...e.members.map((m) => m.num));
    const arr = new Array(maxNum + 1).fill('undefined');
    for (const m of e.members) arr[m.num] = `'${m.name}'`;
    L.push(`const ${e.name}_FROM_NUM: readonly (${TP}${e.name} | undefined)[] = [${arr.join(', ')}];`);
    L.push(`function enc_${e.name}(v: ${TP}${e.name}): number { const n = ${e.name}_TO_NUM[v]; if (n === undefined) throw new RangeError('${e.name}: invalid value ' + String(v)); return n; }`);
    L.push(`function dec_${e.name}(n: number): ${TP}${e.name} { const v = ${e.name}_FROM_NUM[n]; if (v === undefined) throw new DecodeError('${e.name}: unknown value ' + n, 'badEnum'); return v; }`);
  }
  L.push('');

  const tsT = (n) => {
    const b = base(model, n);
    if (SCALARS.has(b)) return tsScalar(model, b);
    return `${TP}${b}`;
  };
  const writeScalar = (cat, t, expr) => {
    const b = base(model, t);
    switch (cat) {
      case 'bool': return `w.bool(${expr});`;
      case 'varint': return b === 'u32' ? `w.u32(${expr});` : `w.u64(${expr});`;
      case 'svarint': return b === 'i32' ? `w.i32(${expr});` : `w.i64(${expr});`;
      case 'enum': return `w.varint(enc_${b}(${expr}));`;
      case 'f32': return `w.f32(${expr});`;
      case 'f64': return `w.f64(${expr});`;
      case 'string': return `w.str(${expr});`;
      case 'bytes': return `w.bytes(${expr});`;
    }
    throw new Error(cat);
  };
  const readScalar = (cat, t) => {
    const b = base(model, t);
    switch (cat) {
      case 'bool': return 'r.bool()';
      case 'varint': return b === 'u32' ? 'r.u32()' : 'r.u64()';
      case 'svarint': return b === 'i32' ? 'r.i32()' : 'r.i64()';
      case 'enum': return `dec_${b}(r.varint())`;
      case 'f32': return 'r.f32()';
      case 'f64': return 'r.f64()';
      case 'string': return 'r.str()';
      case 'bytes': return 'r.bytes()';
    }
    throw new Error(cat);
  };
  const writeKey = (key) => (key < 128 ? `w.byte(${key});` : `w.varint(${key});`);
  const writeValue = (t, expr) => {
    const cat = category(model, t);
    const b = base(model, t);
    if (cat === 'struct' || cat === 'union') return `{ const s = w.beginLd(); enc${cat === 'struct' ? 'S' : 'U'}_${b}(w, ${expr}); w.endLd(s); }`;
    return writeScalar(cat, t, expr);
  };
  const readValue = (t) => {
    const cat = category(model, t);
    const b = base(model, t);
    if (cat === 'struct') return `decS_${b}(r, r.ldEnd(), {})`;
    if (cat === 'union') return `decU_${b}(r, r.ldEnd())`;
    return readScalar(cat, t);
  };

  for (const s of model.structs.values()) {
    const fs = sortedFields(s);
    // encoder
    L.push(`function encS_${s.name}(w: Writer, v: ${TP}${s.name}): void {`);
    if (fs.length === 0) L.push('  void w; void v;');
    for (const f of fs) {
      const cat = category(model, f.type.name);
      const acc = `v.${f.name}`;
      if (f.type.list) {
        if (isPackable(cat)) {
          const key = keyOf(f.num, cat, true);
          if (cat === 'f64' || cat === 'f32') {
            const sz = cat === 'f64' ? 8 : 4;
            L.push(`  { const a = ${acc}; if (a.length) { ${writeKey(key)} w.varint(a.length * ${sz}); for (let i = 0; i < a.length; i++) w.${cat}(a[i]!); } }`);
          } else {
            L.push(`  { const a = ${acc}; if (a.length) { ${writeKey(key)} const s = w.beginLd(); for (let i = 0; i < a.length; i++) ${writeScalar(cat, f.type.name, 'a[i]!')} w.endLd(s); } }`);
          }
        } else {
          const key = keyOf(f.num, cat, false);
          L.push(`  { const a = ${acc}; for (let i = 0; i < a.length; i++) { ${writeKey(key)} ${writeValue(f.type.name, 'a[i]!')} } }`);
        }
      } else {
        const key = keyOf(f.num, cat, false);
        const body = `${writeKey(key)} ${writeValue(f.type.name, acc)}`;
        if (f.optional) L.push(`  if (${acc} !== undefined) { ${body} }`);
        else L.push(`  ${body}`);
      }
    }
    L.push('}');
    // decoder: fills `o` (so a flat union can pre-seed its `type`)
    L.push(`function decS_${s.name}(r: Reader, end: number, o: any): ${TP}${s.name} {`);
    for (const f of fs) if (f.type.list) L.push(`  const l_${f.name}: ${tsT(f.type.name)}[] = [];`);
    const req = fs.filter((f) => !f.type.list && !f.optional);
    for (const f of req) L.push(`  let h_${f.name} = false;`);
    for (const f of fs) if (!f.type.list) L.push(`  let v_${f.name}: ${tsT(f.type.name)} | undefined;`);
    L.push('  while (r.pos < end) {');
    L.push('    const key = r.varint();');
    L.push('    switch (key) {');
    for (const f of fs) {
      const cat = category(model, f.type.name);
      if (f.type.list) {
        if (isPackable(cat)) {
          L.push(`      case ${keyOf(f.num, cat, true)}: { const e = r.ldEnd(); while (r.pos < e) l_${f.name}.push(${readScalar(cat, f.type.name)}); r.expectAt(e); break; }`);
        } else {
          L.push(`      case ${keyOf(f.num, cat, false)}: l_${f.name}.push(${readValue(f.type.name)}); break;`);
        }
      } else {
        const set = req.includes(f) ? ` h_${f.name} = true;` : '';
        L.push(`      case ${keyOf(f.num, cat, false)}: v_${f.name} = ${readValue(f.type.name)};${set} break;`);
      }
    }
    L.push('      default: r.skip(key);');
    L.push('    }');
    L.push('  }');
    L.push(`  r.expectAt(end);`);
    for (const f of req) L.push(`  if (!h_${f.name}) throw new DecodeError('${s.name}.${f.name}: missing', 'missingField');`);
    for (const f of fs) {
      if (f.type.list) L.push(`  o.${f.name} = l_${f.name};`);
      else if (f.optional) L.push(`  if (v_${f.name} !== undefined) o.${f.name} = v_${f.name};`);
      else L.push(`  o.${f.name} = v_${f.name};`);
    }
    L.push('  return o;');
    L.push('}');
  }

  for (const u of model.unions.values()) {
    const vs = sortedVariants(u);
    const tag = u.flat ? 'type' : 'kind';
    L.push(`function encU_${u.name}(w: Writer, v: ${TP}${u.name}): void {`);
    L.push(`  switch (v.${tag}) {`);
    for (const x of vs) {
      if (x.type === 'void') { L.push(`    case '${x.name}': w.varint(${x.num * 8 + 2}); w.byte(0); return;`); continue; }
      const cat = category(model, x.type);
      const key = keyOf(x.num, cat, false);
      const expr = u.flat ? 'v' : 'v.value';
      L.push(`    case '${x.name}': ${writeKey(key)} ${writeValue(x.type, expr)} return;`);
    }
    L.push(`    default: throw new RangeError('${u.name}: unknown ${tag} ' + String((v as { ${tag}?: unknown }).${tag}));`);
    L.push('  }');
    L.push('}');
    L.push(`function decU_${u.name}(r: Reader, end: number): ${TP}${u.name} {`);
    L.push(`  let out: ${TP}${u.name} | undefined;`);
    L.push('  while (r.pos < end) {');
    L.push('    const key = r.varint();');
    L.push(`    if (out !== undefined && key >>> 3 !== 0) throw new DecodeError('${u.name}: more than one variant');`);
    L.push('    switch (key) {');
    for (const x of vs) {
      if (x.type === 'void') {
        L.push(`      case ${x.num * 8 + 2}: { const e = r.ldEnd(); r.pos = e; out = { kind: '${x.name}' } as ${TP}${u.name}; break; }`);
        continue;
      }
      const cat = category(model, x.type);
      const key = keyOf(x.num, cat, false);
      if (u.flat) {
        L.push(`      case ${key}: out = decS_${base(model, x.type)}(r, r.ldEnd(), { type: '${x.name}' }) as ${TP}${u.name}; break;`);
      } else {
        L.push(`      case ${key}: out = { kind: '${x.name}', value: ${readValue(x.type)} } as ${TP}${u.name}; break;`);
      }
    }
    L.push('      default: r.skip(key);');
    L.push('    }');
    L.push('  }');
    L.push('  r.expectAt(end);');
    L.push(`  if (out === undefined) throw new DecodeError('${u.name}: no known variant (newer peer?)', 'unknownVariant');`);
    L.push('  return out;');
    L.push('}');
  }
  L.push('');

  // Public codec table.
  L.push('/** Encode / decode any schema struct or union as a standalone message. */');
  L.push('export interface Codec<V> { encode(v: V): Uint8Array; decode(bytes: Uint8Array): V; }');
  L.push('');
  L.push('const shared = new Writer(1024);');
  L.push('function mk<V>(enc: (w: Writer, v: V) => void, dec: (r: Reader, end: number) => V): Codec<V> {');
  L.push('  return {');
  L.push('    encode(v: V): Uint8Array { shared.reset(); enc(shared, v); return shared.finish(); },');
  L.push('    decode(bytes: Uint8Array): V { const r = new Reader(bytes); return dec(r, bytes.length); },');
  L.push('  };');
  L.push('}');
  L.push('');
  L.push('export const codecs = {');
  for (const n of typeNames) {
    if (model.structs.has(n)) L.push(`  ${n}: mk<${TP}${n}>(encS_${n}, (r, e) => decS_${n}(r, e, {})),`);
    else L.push(`  ${n}: mk<${TP}${n}>(encU_${n}, decU_${n}),`);
  }
  L.push('} as const;');
  L.push('');
  L.push('export type CodecName = keyof typeof codecs;');
  if (!envelope) return L.join('\n') + '\n';
  L.push('');
  L.push('/** Encode into a caller-owned writer (no copy); the transport frames it. */');
  L.push('export function encodeEngineMessageInto(w: Writer, v: T.EngineMessage): void { encU_EngineMessage(w, v); }');
  L.push('export const encodeEngineMessage = (v: T.EngineMessage): Uint8Array => codecs.EngineMessage.encode(v);');
  L.push('export const decodeEngineMessage = (bytes: Uint8Array): T.EngineMessage => codecs.EngineMessage.decode(bytes);');
  return L.join('\n') + '\n';
}

/**
 * A self-contained TypeScript module for ONE schema family: its types and codec
 * in one file, importing the wire runtime from `wireImport`. For code that
 * cannot import packages/engine-api — Electron main is its own CommonJS
 * TypeScript project (electron/tsconfig.json, rootDir `.`), and it speaks the
 * frame channel itself. The family must be closed: it may reference scalars,
 * aliases and its own types only.
 */
function genTsFamilyModule(model, family, wireImport) {
  const own = (m) => [...m.values()].filter((x) => x.family === family && !x.synthetic);
  const enums = own(model.enums);
  const structs = own(model.structs);
  const unions = own(model.unions);
  if (!structs.length && !unions.length) throw new Error(`family ${family}: nothing to generate`);
  const names = new Set([...enums, ...structs, ...unions].map((x) => x.name));
  const needAlias = new Set();
  const check = (t, where) => {
    if (SCALARS.has(t) || t === 'void' || names.has(t)) return;
    if (model.aliases.has(t)) { needAlias.add(t); return; }
    throw new Error(`family ${family} is not closed: ${where} references ${t}`);
  };
  for (const s of structs) for (const f of s.fields) check(f.type.name, `${s.name}.${f.name}`);
  for (const u of unions) for (const v of u.variants) check(v.type, `${u.name}.${v.name}`);
  const sub = {
    version: model.version,
    aliases: new Map([...model.aliases].filter(([n]) => needAlias.has(n))),
    enums: new Map(enums.map((e) => [e.name, e])),
    structs: new Map(structs.map((s) => [s.name, s])),
    unions: new Map(unions.map((u) => [u.name, u])),
    commands: [],
    queries: [],
    events: [],
    order: model.order.filter((o) => names.has(o.name)),
  };
  let out = `/* eslint-disable */\n// ${HEADER_NOTE}\n//\n// Family "${family}" only — a standalone copy for code that cannot import packages/engine-api.\n\n`;
  // Types: everything genTsTypes emits except the command/query/event maps (none here).
  const types = genTsTypes(sub).split('/** Arguments of each command, by name. */')[0].replace(/^\/\* eslint-disable \*\/\n\/\/ .*\n\n/, '');
  const [importLine, ...codec] = genTsCodec(sub, { wireImport, typesImport: null, envelope: false, header: false }).split('\n');
  out += `${importLine}\n\n`;
  out += types.trimEnd() + '\n';
  out += codec.join('\n');
  return out;
}

/** The wire runtime, copied for a standalone family module's project. */
function genTsWireCopy() {
  const src = readFileSync(join(__dirname, '..', 'src', 'wire.ts'), 'utf8').replace(/\r\n/g, '\n');
  return `// COPIED by packages/engine-api/codegen/generate.cjs from packages/engine-api/src/wire.ts — do not edit; run \`npm run engine-api:gen\`.\n\n${src}`;
}

function genTsMeta(model) {
  const L = [];
  L.push(`// ${HEADER_NOTE}`);
  L.push('');
  L.push(`import type { CommandType, QueryType, EventType } from './types';`);
  L.push('');
  L.push('/**');
  L.push(' * How a command relates to history:');
  L.push(' *  - edit     changes the document; one undo entry (or part of the open gesture / batch)');
  L.push(' *  - control  history, gestures, transport, viewport, session — never an undo entry');
  L.push(' *  - io       project lifecycle (open/save/new) — not undoable, clears or keeps history as documented');
  L.push(' */');
  L.push(`export type CommandKind = 'edit' | 'control' | 'io';`);
  L.push('');
  L.push('export interface CommandInfo { readonly id: number; readonly kind: CommandKind; readonly coalesce: boolean; readonly family: string; readonly result: string; readonly doc: string; }');
  L.push('export interface QueryInfo { readonly id: number; readonly family: string; readonly result: string; readonly doc: string; }');
  L.push('export interface EventInfo { readonly id: number; readonly ephemeral: boolean; readonly family: string; readonly doc: string; }');
  L.push('');
  const q = (s) => JSON.stringify(s);
  L.push('export const COMMANDS: Readonly<Record<CommandType, CommandInfo>> = {');
  for (const c of model.commands) {
    const kind = c.attrs.has('control') ? 'control' : c.attrs.has('io') ? 'io' : 'edit';
    L.push(`  ${c.name}: { id: ${c.id}, kind: '${kind}', coalesce: ${c.attrs.has('coalesce')}, family: ${q(c.family)}, result: ${q(c.result ?? 'Empty')}, doc: ${q(c.doc.join(' '))} },`);
  }
  L.push('};');
  L.push('');
  L.push('export const QUERIES: Readonly<Record<QueryType, QueryInfo>> = {');
  for (const c of model.queries) L.push(`  ${c.name}: { id: ${c.id}, family: ${q(c.family)}, result: ${q(c.result)}, doc: ${q(c.doc.join(' '))} },`);
  L.push('};');
  L.push('');
  L.push('export const EVENTS: Readonly<Record<EventType, EventInfo>> = {');
  for (const c of model.events) L.push(`  ${c.name}: { id: ${c.id}, ephemeral: ${c.attrs.has('ephemeral')}, family: ${q(c.family)}, doc: ${q(c.doc.join(' '))} },`);
  L.push('};');
  L.push('');
  const counts = { enums: model.enums.size, structs: model.structs.size, unions: model.unions.size, commands: model.commands.length, queries: model.queries.length, events: model.events.length };
  L.push(`/** Size of the schema, for docs and tests. */`);
  L.push(`export const SCHEMA_COUNTS = ${JSON.stringify(counts)} as const;`);
  return L.join('\n') + '\n';
}


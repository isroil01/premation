function loadSchema(dir = SCHEMA_DIR) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.eapi'))
    .sort()
    .map((f) => ({ name: `schema/${f}`, src: readFileSync(join(dir, f), 'utf8') }));
  if (files.length === 0) throw new Error(`no .eapi files in ${dir}`);
  return parse(files);
}

/** Every generated file: absolute path → contents. */
function generateAll(model = loadSchema()) {
  return {
    [join(TS_OUT, 'types.ts')]: genTsTypes(model),
    [join(TS_OUT, 'codec.ts')]: genTsCodec(model),
    [join(TS_OUT, 'meta.ts')]: genTsMeta(model),
    [join(CPP_OUT, 'engine_api.hpp')]: genCppHeader(model),
    [join(CPP_OUT, 'engine_api.cpp')]: genCppSource(model),
    [join(CPP_OUT, 'fixtures.inc')]: genFixtures(model),
    // Electron main speaks the frame channel (schema 95_frames.eapi) itself.
    [join(ELECTRON_OUT, 'engineWire.ts')]: genTsWireCopy(),
    [join(ELECTRON_OUT, 'frameChannel.ts')]: genTsFamilyModule(model, 'FrameChannel', './engineWire'),
  };
}

/** Normalise line endings so a CRLF checkout does not read as stale. */
function sameText(a, b) { return a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n'); }

function staleFiles(model) {
  const out = [];
  for (const [path, text] of Object.entries(generateAll(model))) {
    if (!existsSync(path) || !sameText(readFileSync(path, 'utf8'), text)) out.push(relative(ROOT, path).replace(/\\/g, '/'));
  }
  return out;
}


function cppIdent(n) { const s = snake(n); return CPP_KEYWORDS.has(s) ? `${s}_` : s; }

function cppScalar(n) {
  switch (n) {
    case 'bool': return 'bool';
    case 'i32': return 'std::int32_t';
    case 'u32': return 'std::uint32_t';
    case 'i64': return 'std::int64_t';
    case 'u64': return 'std::uint64_t';
    case 'f32': return 'float';
    case 'f64': return 'double';
    case 'string': return 'std::string';
    case 'bytes': return 'std::vector<std::uint8_t>';
  }
  return null;
}

function cppT(model, n) { return cppScalar(n) ?? n; }

function cppDefault(model, n) {
  const b = base(model, n);
  switch (b) {
    case 'bool': return ' = false';
    case 'i32': case 'u32': case 'i64': case 'u64': return ' = 0';
    case 'f32': return ' = 0.0F';
    case 'f64': return ' = 0.0';
    default:
      if (model.enums.has(b)) {
        const e = model.enums.get(b);
        return ` = ${b}::${cppIdent(e.members.find((m) => m.num === 0).name)}`;
      }
      return '';
  }
}

/** Topological order so by-value members are complete; list edges are soft (std::vector allows incomplete T). */
function cppOrder(model) {
  const deps = new Map();
  const add = (n, d) => deps.get(n).add(d);
  for (const s of model.structs.values()) {
    deps.set(s.name, new Set());
  }
  for (const u of model.unions.values()) deps.set(u.name, new Set());
  for (const s of model.structs.values()) {
    for (const f of s.fields) {
      const b = base(model, f.type.name);
      if ((model.structs.has(b) || model.unions.has(b)) && !f.type.list) add(s.name, b);
      if ((model.structs.has(b) || model.unions.has(b)) && f.type.list && b !== s.name) add(s.name, b);
    }
  }
  for (const u of model.unions.values()) {
    for (const v of u.variants) {
      const b = v.type === 'void' ? null : base(model, v.type);
      if (b && (model.structs.has(b) || model.unions.has(b))) add(u.name, b);
    }
  }
  const out = [];
  const state = new Map();
  const visit = (n, chain) => {
    if (state.get(n) === 2) return;
    if (state.get(n) === 1) throw new Error(`C++: by-value cycle ${[...chain, n].join(' → ')}`);
    state.set(n, 1);
    for (const d of deps.get(n)) visit(d, [...chain, n]);
    state.set(n, 2);
    out.push(n);
  };
  for (const o of model.order) if (o.kind !== 'enum') visit(o.name, []);
  return out;
}

function genCppHeader(model) {
  const L = [];
  L.push(`// ${HEADER_NOTE}`);
  L.push('//');
  L.push('// Plain structs + a canonical binary codec for the Premation engine API');
  L.push('// (docs/ENGINE_API.md). No exceptions: decode returns a wire::Status.');
  L.push('');
  L.push('#ifndef PREMATION_PROTOCOL_ENGINE_API_HPP');
  L.push('#define PREMATION_PROTOCOL_ENGINE_API_HPP');
  L.push('');
  L.push('#include <cstdint>');
  L.push('#include <optional>');
  L.push('#include <span>');
  L.push('#include <string>');
  L.push('#include <string_view>');
  L.push('#include <variant>');
  L.push('#include <vector>');
  L.push('');
  L.push('#include "premation/protocol/wire.hpp"');
  L.push('');
  L.push('namespace premation::api {');
  L.push('');
  L.push(`inline constexpr std::uint32_t kProtocolMajor = ${model.version.major};`);
  L.push(`inline constexpr std::uint32_t kProtocolMinor = ${model.version.minor};`);
  L.push('');
  for (const a of model.aliases.values()) L.push(`using ${a.name} = ${cppScalar(a.target)};`);
  L.push('');
  for (const e of model.enums.values()) {
    L.push(`enum class ${e.name} : std::uint32_t {`);
    for (const m of e.members) L.push(`  ${cppIdent(m.name)} = ${m.num},`);
    L.push('};');
    L.push(`[[nodiscard]] std::string_view to_string(${e.name} v) noexcept;`);
    L.push(`[[nodiscard]] bool from_u32(std::uint32_t n, ${e.name}& out) noexcept;`);
    L.push('');
  }
  const order = cppOrder(model);
  for (const n of order) L.push(`struct ${n};`);
  L.push('');
  const fieldType = (f) => {
    const t = cppT(model, f.type.name);
    if (f.type.list) return `std::vector<${t}>`;
    if (f.optional) return `std::optional<${t}>`;
    return t;
  };
  for (const n of order) {
    if (model.structs.has(n)) {
      const s = model.structs.get(n);
      L.push(`struct ${n} {`);
      for (const f of s.fields) {
        const d = !f.type.list && !f.optional ? cppDefault(model, f.type.name) : '';
        L.push(`  ${fieldType(f)} ${cppIdent(f.name)}${d};`);
      }
      L.push(`  bool operator==(const ${n}&) const = default;`);
      L.push('};');
    } else {
      const u = model.unions.get(n);
      const vs = u.variants;
      L.push(`struct ${n} {`);
      L.push('  enum class Kind : std::uint32_t {');
      for (const v of vs) L.push(`    ${cppIdent(v.name)} = ${v.num},`);
      L.push('  };');
      L.push(`  std::variant<${vs.map((v) => (v.type === 'void' ? 'std::monostate' : cppT(model, v.type))).join(', ')}> v;`);
      L.push(`  [[nodiscard]] Kind kind() const noexcept;`);
      L.push(`  bool operator==(const ${n}&) const = default;`);
      L.push('};');
    }
    L.push('');
  }
  for (const n of order) {
    L.push(`void encode(wire::Writer& w, const ${n}& v);`);
    L.push(`[[nodiscard]] wire::Status decode(wire::Reader& r, ${n}& out);`);
  }
  L.push('');
  L.push('/// Decode `bytes` as the message type named `type`, re-encode it into `out`.');
  L.push('/// Used by the cross-language round-trip test; unknown names return bad_type.');
  L.push('[[nodiscard]] wire::Status roundtrip_by_name(std::string_view type, std::span<const std::uint8_t> bytes, std::vector<std::uint8_t>& out);');
  L.push('');
  L.push('/// Every message type name, for tests and fuzzers.');
  L.push('[[nodiscard]] std::span<const std::string_view> message_type_names() noexcept;');
  L.push('');
  L.push('}  // namespace premation::api');
  L.push('');
  L.push('#endif  // PREMATION_PROTOCOL_ENGINE_API_HPP');
  return L.join('\n') + '\n';
}

function genCppSource(model) {
  const L = [];
  L.push(`// ${HEADER_NOTE}`);
  L.push('');
  L.push('#include "engine_api.hpp"');
  L.push('');
  L.push('#include <array>');
  L.push('#include <utility>');
  L.push('');
  L.push('namespace premation::api {');
  L.push('');
  L.push('using wire::Status;');
  L.push('');
  for (const e of model.enums.values()) {
    L.push(`std::string_view to_string(${e.name} v) noexcept {`);
    L.push('  switch (v) {');
    for (const m of e.members) L.push(`    case ${e.name}::${cppIdent(m.name)}: return "${m.name}";`);
    L.push('  }');
    L.push('  return {};');
    L.push('}');
    L.push(`bool from_u32(std::uint32_t n, ${e.name}& out) noexcept {`);
    L.push('  switch (n) {');
    for (const m of e.members) L.push(`    case ${m.num}: out = ${e.name}::${cppIdent(m.name)}; return true;`);
    L.push('    default: return false;');
    L.push('  }');
    L.push('}');
  }
  L.push('');
  const order = cppOrder(model);

  const writeKey = (key) => `w.varint(${key}U);`;
  const writeScalar = (cat, t, expr) => {
    const b = base(model, t);
    switch (cat) {
      case 'bool': return `w.boolean(${expr});`;
      case 'varint': return `w.varint(${expr});`;
      case 'svarint': return `w.svarint(${expr});`;
      case 'enum': return `w.varint(static_cast<std::uint32_t>(${expr}));`;
      case 'f32': return `w.f32(${expr});`;
      case 'f64': return `w.f64(${expr});`;
      case 'string': return `w.str(${expr});`;
      case 'bytes': return `w.bytes(${expr});`;
    }
    throw new Error(cat + b);
  };
  const writeValue = (t, expr) => {
    const cat = category(model, t);
    if (cat === 'struct' || cat === 'union') return `{ const std::size_t s = w.begin_ld(); encode(w, ${expr}); w.end_ld(s); }`;
    return writeScalar(cat, t, expr);
  };
  /** Statement(s) that read one value into lvalue `dst`; return Status on failure. */
  const readInto = (t, dst) => {
    const cat = category(model, t);
    const b = base(model, t);
    switch (cat) {
      case 'bool': return `if (!r.boolean(${dst})) return Status::truncated;`;
      case 'varint': return b === 'u32' ? `if (!r.u32(${dst})) return Status::bad_value;` : `if (!r.varint(${dst})) return Status::truncated;`;
      case 'svarint': return b === 'i32' ? `if (!r.i32(${dst})) return Status::bad_value;` : `if (!r.svarint(${dst})) return Status::truncated;`;
      case 'enum': return `{ std::uint32_t n = 0; if (!r.u32(n)) return Status::bad_value; if (!from_u32(n, ${dst})) return Status::bad_enum; }`;
      case 'f32': return `if (!r.f32(${dst})) return Status::truncated;`;
      case 'f64': return `if (!r.f64(${dst})) return Status::truncated;`;
      case 'string': return `if (!r.str(${dst})) return Status::truncated;`;
      case 'bytes': return `if (!r.bytes(${dst})) return Status::truncated;`;
      case 'struct':
      case 'union':
        return `{ wire::Reader sub; if (!r.ld(sub)) return Status::truncated; if (const Status st = decode(sub, ${dst}); st != Status::ok) return st; }`;
    }
    throw new Error(cat);
  };

  for (const n of order) {
    if (model.structs.has(n)) {
      const s = model.structs.get(n);
      const fs = sortedFields(s);
      L.push(`void encode(wire::Writer& w, const ${n}& v) {`);
      if (fs.length === 0) L.push('  (void)w;', '  (void)v;');
      for (const f of fs) {
        const cat = category(model, f.type.name);
        const acc = `v.${cppIdent(f.name)}`;
        if (f.type.list) {
          if (isPackable(cat)) {
            const key = keyOf(f.num, cat, true);
            if (cat === 'bool') {
              L.push(`  if (!${acc}.empty()) { ${writeKey(key)} const std::size_t s = w.begin_ld(); for (const bool e : ${acc}) w.boolean(e); w.end_ld(s); }`);
            } else {
              L.push(`  if (!${acc}.empty()) { ${writeKey(key)} const std::size_t s = w.begin_ld(); for (const auto& e : ${acc}) ${writeScalar(cat, f.type.name, 'e')} w.end_ld(s); }`);
            }
          } else {
            const key = keyOf(f.num, cat, false);
            L.push(`  for (const auto& e : ${acc}) { ${writeKey(key)} ${writeValue(f.type.name, 'e')} }`);
          }
        } else {
          const key = keyOf(f.num, cat, false);
          if (f.optional) L.push(`  if (${acc}.has_value()) { ${writeKey(key)} ${writeValue(f.type.name, `*${acc}`)} }`);
          else L.push(`  ${writeKey(key)} ${writeValue(f.type.name, acc)}`);
        }
      }
      L.push('}');
      L.push('');
      L.push(`Status decode(wire::Reader& r, ${n}& out) {`);
      const req = fs.filter((f) => !f.type.list && !f.optional);
      if (fs.length === 0) L.push('  (void)out;');
      for (const f of req) L.push(`  bool has_${cppIdent(f.name)} = false;`);
      L.push('  while (!r.at_end()) {');
      L.push('    std::uint64_t key = 0;');
      L.push('    if (!r.varint(key)) return Status::truncated;');
      L.push('    switch (key) {');
      for (const f of fs) {
        const cat = category(model, f.type.name);
        const acc = `out.${cppIdent(f.name)}`;
        const elemT = cppT(model, f.type.name);
        if (f.type.list) {
          if (isPackable(cat)) {
            L.push(`      case ${keyOf(f.num, cat, true)}U: {`);
            L.push('        wire::Reader sub;');
            L.push('        if (!r.ld(sub)) return Status::truncated;');
            L.push(`        while (!sub.at_end()) { ${elemT} e${cppDefault(model, f.type.name)}; ${readInto(f.type.name, 'e').replace(/\br\./g, 'sub.')} ${acc}.push_back(e); }`);
            L.push('        break;');
            L.push('      }');
          } else {
            L.push(`      case ${keyOf(f.num, cat, false)}U: {`);
            // Decode in place: no temporary + move per element (the output is discarded on any error).
            L.push(`        auto& e = ${acc}.emplace_back();`);
            L.push(`        ${readInto(f.type.name, 'e')}`);
            L.push('        break;');
            L.push('      }');
          }
        } else if (f.optional) {
          L.push(`      case ${keyOf(f.num, cat, false)}U: {`);
          L.push(`        ${elemT} e${cppDefault(model, f.type.name)};`);
          L.push(`        ${readInto(f.type.name, 'e')}`);
          L.push(`        ${acc} = std::move(e);`);
          L.push('        break;');
          L.push('      }');
        } else {
          L.push(`      case ${keyOf(f.num, cat, false)}U: {`);
          L.push(`        ${readInto(f.type.name, acc)}`);
          L.push(`        has_${cppIdent(f.name)} = true;`);
          L.push('        break;');
          L.push('      }');
        }
      }
      L.push('      default:');
      L.push('        if (!r.skip(key)) return Status::truncated;');
      L.push('        break;');
      L.push('    }');
      L.push('  }');
      for (const f of req) L.push(`  if (!has_${cppIdent(f.name)}) return Status::missing_field;`);
      L.push('  return Status::ok;');
      L.push('}');
      L.push('');
    } else {
      const u = model.unions.get(n);
      const vs = u.variants;
      L.push(`${n}::Kind ${n}::kind() const noexcept {`);
      L.push(`  static constexpr std::array<Kind, ${vs.length}> kKinds = {${vs.map((v) => `Kind::${cppIdent(v.name)}`).join(', ')}};`);
      L.push('  return kKinds[v.index()];');
      L.push('}');
      L.push('');
      L.push(`void encode(wire::Writer& w, const ${n}& v) {`);
      L.push('  switch (v.v.index()) {');
      vs.forEach((x, i) => {
        if (x.type === 'void') { L.push(`    case ${i}: w.varint(${x.num * 8 + 2}U); w.varint(0U); return;`); return; }
        const cat = category(model, x.type);
        L.push(`    case ${i}: ${writeKey(keyOf(x.num, cat, false))} ${writeValue(x.type, `std::get<${i}>(v.v)`)} return;`);
      });
      L.push('    default: return;');
      L.push('  }');
      L.push('}');
      L.push('');
      L.push(`Status decode(wire::Reader& r, ${n}& out) {`);
      L.push('  bool seen = false;');
      L.push('  while (!r.at_end()) {');
      L.push('    std::uint64_t key = 0;');
      L.push('    if (!r.varint(key)) return Status::truncated;');
      L.push('    switch (key) {');
      vs.forEach((x, i) => {
        if (x.type === 'void') {
          L.push(`      case ${x.num * 8 + 2}U: {`);
          L.push('        if (seen) return Status::multiple_variants;');
          L.push('        wire::Reader sub;');
          L.push('        if (!r.ld(sub)) return Status::truncated;');
          L.push(`        out.v.emplace<${i}>();`);
          L.push('        seen = true;');
          L.push('        break;');
          L.push('      }');
          return;
        }
        const cat = category(model, x.type);
        L.push(`      case ${keyOf(x.num, cat, false)}U: {`);
        L.push('        if (seen) return Status::multiple_variants;');
        L.push(`        ${cppT(model, x.type)} e${cppDefault(model, x.type)};`);
        L.push(`        ${readInto(x.type, 'e')}`);
        L.push(`        out.v.emplace<${i}>(std::move(e));`);
        L.push('        seen = true;');
        L.push('        break;');
        L.push('      }');
      });
      L.push('      default:');
      L.push('        if (!r.skip(key)) return Status::truncated;');
      L.push('        break;');
      L.push('    }');
      L.push('  }');
      L.push('  return seen ? Status::ok : Status::unknown_variant;');
      L.push('}');
      L.push('');
    }
  }

  const names = messageTypes(model);
  L.push('namespace {');
  L.push('template <class M>');
  L.push('Status roundtrip(std::span<const std::uint8_t> bytes, std::vector<std::uint8_t>& out) {');
  L.push('  M m{};');
  L.push('  wire::Reader r(bytes);');
  L.push('  if (const Status st = decode(r, m); st != Status::ok) return st;');
  L.push('  wire::Writer w;');
  L.push('  encode(w, m);');
  L.push('  out = w.take();');
  L.push('  return Status::ok;');
  L.push('}');
  L.push(`constexpr std::array<std::string_view, ${names.length}> kNames = {`);
  for (const n of names) L.push(`    "${n}",`);
  L.push('};');
  L.push('}  // namespace');
  L.push('');
  L.push('std::span<const std::string_view> message_type_names() noexcept { return kNames; }');
  L.push('');
  L.push('Status roundtrip_by_name(std::string_view type, std::span<const std::uint8_t> bytes, std::vector<std::uint8_t>& out) {');
  for (const n of names) L.push(`  if (type == "${n}") return roundtrip<${n}>(bytes, out);`);
  L.push('  return Status::bad_type;');
  L.push('}');
  L.push('');
  L.push('}  // namespace premation::api');
  return L.join('\n') + '\n';
}

function genFixtures(model) {
  const reflect = makeReflect(model);
  const sampler = makeSampler(model);
  const L = [];
  L.push(`// ${HEADER_NOTE}`);
  L.push('//');
  L.push('// One canonical encoding per sample value of every message type, produced by');
  L.push('// the generator\'s reflective encoder. The TypeScript test proves the generated');
  L.push('// TS codec emits these same bytes; native/protocol/tests proves the C++ codec');
  L.push('// decodes and re-encodes each to the identical bytes.');
  L.push('// Entry: { type name, sample label, bytes }.');
  L.push('');
  let count = 0;
  for (const n of messageTypes(model)) {
    for (const s of sampler.samplesFor(n)) {
      const b = reflect.encode(n, s.value);
      const hex = [];
      for (let i = 0; i < b.length; i++) hex.push(`0x${b[i].toString(16).padStart(2, '0')}`);
      L.push(`PREMATION_FIXTURE("${n}", "${s.label}", ${hex.length ? hex.join(',') : ''})`);
      count++;
    }
  }
  L.push(`// ${count} fixtures`);
  return L.join('\n') + '\n';
}


/**
 * Engine API code generator — `npm run engine-api:gen`.
 *
 * Reads the schema (packages/engine-api/schema/*.eapi, in file-name order) and
 * writes, from that ONE source:
 *
 *   packages/engine-api/src/generated/types.ts     TypeScript types
 *   packages/engine-api/src/generated/codec.ts     TypeScript binary codec
 *   packages/engine-api/src/generated/meta.ts      reflection: versions, command table
 *   native/protocol/generated/engine_api.hpp       C++ structs + codec declarations
 *   native/protocol/generated/engine_api.cpp       C++ codec
 *   native/protocol/generated/fixtures.inc         cross-language round-trip vectors
 *   electron/generated/frameChannel.ts             the FrameChannel family, standalone (Electron main)
 *   electron/generated/engineWire.ts               a copy of src/wire.ts for it
 *
 *   node packages/engine-api/codegen/generate.cjs          write the files
 *   node packages/engine-api/codegen/generate.cjs --check  exit 1 if any is stale
 *
 * CommonJS (like scripts/featureCounts.cjs) so the Jest staleness test can
 * `require` it and compare in memory instead of re-implementing it, and so it
 * runs on CI's Node 20 with no TypeScript loader and no native tool (flatc,
 * protoc) — docs/ENGINE_API.md §9 has the measured reasons.
 *
 * The wire format is documented in docs/ENGINE_API.md §9. In short: the
 * protobuf wire encoding (varint keys `field << 3 | wireType`, zigzag signed
 * ints, little-endian fixed32/fixed64 floats, length-delimited strings /
 * messages / packed numeric lists) with a CANONICAL encoder — fields in
 * field-number order, required fields always written, absent optionals and
 * empty lists never written — so the TypeScript and C++ encoders produce the
 * same bytes for the same value. `fixtures.inc` is how that is proven.
 */


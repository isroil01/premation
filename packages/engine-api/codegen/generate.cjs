// Type helpers shared by every backend
// ─────────────────────────────────────────────────────────────────────────────

function pascal(s) { return s[0].toUpperCase() + s.slice(1); }
function snake(s) {
  return s.replace(/-/g, '_').replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').toLowerCase();
}

/** Resolve aliases down to a scalar / named type. */
function base(model, n) { return model.aliases.has(n) ? model.aliases.get(n).target : n; }

/** 'varint' | 'svarint' | 'bool' | 'f32' | 'f64' | 'string' | 'bytes' | 'enum' | 'struct' | 'union' */
function category(model, n) {
  const b = base(model, n);
  switch (b) {
    case 'bool': return 'bool';
    case 'u32': case 'u64': return 'varint';
    case 'i32': case 'i64': return 'svarint';
    case 'f32': return 'f32';
    case 'f64': return 'f64';
    case 'string': return 'string';
    case 'bytes': return 'bytes';
    default:
      if (model.enums.has(b)) return 'enum';
      if (model.structs.has(b)) return 'struct';
      if (model.unions.has(b)) return 'union';
      throw new Error(`unknown type ${n}`);
  }
}

const WT = { varint: 0, svarint: 0, bool: 0, enum: 0, f64: 1, f32: 5, string: 2, bytes: 2, struct: 2, union: 2 };
function isPackable(cat) { return cat === 'varint' || cat === 'svarint' || cat === 'bool' || cat === 'enum' || cat === 'f32' || cat === 'f64'; }
function keyOf(num, cat, list) { return num * 8 + (list && isPackable(cat) ? 2 : WT[cat]); }

function sortedFields(s) { return [...s.fields].sort((a, b) => a.num - b.num); }
function sortedVariants(u) { return [...u.variants].sort((a, b) => a.num - b.num); }

function varintBytes(n) {
  const out = [];
  let v = n;
  while (v >= 128) { out.push((v % 128) + 128); v = Math.floor(v / 128); }
  out.push(v);
  return out;
}


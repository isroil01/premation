function makeReflect(model) {
  const bytes = [];
  const pushVarint = (n) => { for (const b of varintBytes(n)) bytes.push(b); };
  const f64le = (x) => { const b = Buffer.alloc(8); b.writeDoubleLE(x); for (const v of b) bytes.push(v); };
  const f32le = (x) => { const b = Buffer.alloc(4); b.writeFloatLE(x); for (const v of b) bytes.push(v); };
  const zig = (n) => (n >= 0 ? n * 2 : -n * 2 - 1);
  const ld = (fn) => {
    const start = bytes.length;
    fn();
    const body = bytes.splice(start);
    pushVarint(body.length);
    for (const b of body) bytes.push(b);
  };
  const enumNum = (t, v) => {
    const m = model.enums.get(base(model, t)).members.find((x) => x.name === v);
    if (!m) throw new Error(`enum ${t}: no member ${v}`);
    return m.num;
  };
  const scalar = (cat, t, v) => {
    switch (cat) {
      case 'bool': pushVarint(v ? 1 : 0); break;
      case 'varint': pushVarint(v); break;
      case 'svarint': pushVarint(zig(v)); break;
      case 'enum': pushVarint(enumNum(t, v)); break;
      case 'f32': f32le(v); break;
      case 'f64': f64le(v); break;
      case 'string': { const b = Buffer.from(v, 'utf8'); pushVarint(b.length); for (const x of b) bytes.push(x); break; }
      case 'bytes': pushVarint(v.length); for (const x of v) bytes.push(x); break;
      default: throw new Error(cat);
    }
  };
  const value = (t, v) => {
    const cat = category(model, t);
    if (cat === 'struct') ld(() => struct(base(model, t), v));
    else if (cat === 'union') ld(() => union(base(model, t), v));
    else scalar(cat, t, v);
  };
  const struct = (n, v) => {
    for (const f of sortedFields(model.structs.get(n))) {
      const cat = category(model, f.type.name);
      const x = v[f.name];
      if (f.type.list) {
        if (!x || x.length === 0) continue;
        if (isPackable(cat)) {
          pushVarint(keyOf(f.num, cat, true));
          ld(() => { for (const e of x) scalar(cat, f.type.name, e); });
        } else {
          for (const e of x) { pushVarint(keyOf(f.num, cat, false)); value(f.type.name, e); }
        }
        continue;
      }
      if (x === undefined) {
        if (f.optional) continue;
        throw new Error(`reflect: ${n}.${f.name} is required`);
      }
      pushVarint(keyOf(f.num, cat, false));
      value(f.type.name, x);
    }
  };
  const union = (n, v) => {
    const u = model.unions.get(n);
    const tag = u.flat ? v.type : v.kind;
    const variant = u.variants.find((x) => x.name === tag);
    if (!variant) throw new Error(`reflect: ${n} has no variant ${tag}`);
    if (variant.type === 'void') { pushVarint(variant.num * 8 + 2); pushVarint(0); return; }
    const cat = category(model, variant.type);
    pushVarint(keyOf(variant.num, cat, false));
    value(variant.type, u.flat ? v : v.value);
  };
  return {
    encode(typeName, v) {
      bytes.length = 0;
      const cat = category(model, typeName);
      if (cat === 'struct') struct(base(model, typeName), v);
      else if (cat === 'union') union(base(model, typeName), v);
      else throw new Error('reflect.encode takes a struct or union');
      return Uint8Array.from(bytes);
    },
  };
}

/** Deterministic PRNG (mulberry32) seeded from a string. */
function rng(seedText) {
  let h = 2166136261;
  for (let i = 0; i < seedText.length; i++) { h ^= seedText.charCodeAt(i); h = Math.imul(h, 16777619); }
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const SAMPLE_STRINGS = ['layer-7f3a', 'Comp 1', 'effects/fx_12/params/radius', 'é漢字😀', '', 'transform/position'];

/**
 * Sample values for a type. `mode` 'full' fills every optional field and gives
 * every list two entries; 'min' leaves optionals absent and lists empty.
 * Recursion is cut off by depth (a list of itself becomes empty).
 */
function makeSampler(model) {
  const sampleScalar = (r, t) => {
    const b = base(model, t);
    switch (b) {
      case 'bool': return r() < 0.5;
      case 'u32': return Math.floor(r() * 4294967295);
      case 'i32': return Math.floor(r() * 4294967295) - 2147483648;
      case 'u64': return Math.floor(r() * 2 ** 53);
      case 'i64': return Math.floor(r() * 2 ** 53) - 2 ** 52;
      case 'f32': return Math.fround((r() - 0.5) * 1e6);
      case 'f64': return (r() - 0.5) * 1e9;
      case 'string': return SAMPLE_STRINGS[Math.floor(r() * SAMPLE_STRINGS.length)];
      case 'bytes': return Uint8Array.from([0, 1, 255, Math.floor(r() * 256)]);
      default: {
        const e = model.enums.get(b);
        return e.members[Math.floor(r() * e.members.length)].name;
      }
    }
  };
  const sample = (r, t, mode, depth, pick) => {
    const cat = category(model, t);
    const b = base(model, t);
    if (cat === 'struct') {
      const s = model.structs.get(b);
      const o = {};
      for (const f of s.fields) {
        if (f.type.list) {
          const n = mode === 'full' && depth < 3 ? 2 : 0;
          o[f.name] = Array.from({ length: n }, () => sample(r, f.type.name, mode, depth + 1));
        } else if (!f.optional || mode === 'full') {
          o[f.name] = sample(r, f.type.name, mode, depth + 1);
        }
      }
      return o;
    }
    if (cat === 'union') {
      const u = model.unions.get(b);
      const v = pick !== undefined ? u.variants[pick] : u.variants[Math.floor(r() * u.variants.length)];
      if (u.flat) return { type: v.name, ...sample(r, v.type, mode, depth + 1) };
      if (v.type === 'void') return { kind: v.name };
      return { kind: v.name, value: sample(r, v.type, mode, depth + 1) };
    }
    return sampleScalar(r, t);
  };
  return {
    /** Every sample for a named struct/union: full + min, and one per union variant. */
    samplesFor(typeName) {
      const out = [];
      const u = model.unions.get(typeName);
      if (u) {
        u.variants.forEach((v, i) => {
          out.push({ label: `${typeName}.${v.name}`, value: sample(rng(`${typeName}.${v.name}`), typeName, 'full', 0, i) });
          if (v.type !== 'void' && model.structs.has(v.type) && model.structs.get(v.type).fields.length) {
            out.push({ label: `${typeName}.${v.name}#min`, value: sample(rng(`${typeName}.${v.name}#min`), typeName, 'min', 0, i) });
          }
        });
      } else {
        out.push({ label: `${typeName}#full`, value: sample(rng(`${typeName}#full`), typeName, 'full', 0) });
        out.push({ label: `${typeName}#min`, value: sample(rng(`${typeName}#min`), typeName, 'min', 0) });
      }
      return out;
    },
  };
}

/** Every struct and union name, in declaration order (the round-trip set). */
function messageTypes(model) {
  return model.order.filter((o) => o.kind === 'struct' || o.kind === 'union').map((o) => o.name);
}


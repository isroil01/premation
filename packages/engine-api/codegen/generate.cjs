// Lexer
// ─────────────────────────────────────────────────────────────────────────────

function lex(src, file) {
  const toks = [];
  let i = 0;
  let line = 1;
  let pendingDoc = [];
  const push = (type, value) => {
    toks.push({ type, value, line, file, doc: type === 'ident' || type === 'string' ? pendingDoc : [] });
    if (type !== 'ident' && type !== 'string') pendingDoc = [];
    else pendingDoc = [];
  };
  while (i < src.length) {
    const c = src[i];
    if (c === '\n') { line++; i++; continue; }
    if (c === ' ' || c === '\t' || c === '\r') { i++; continue; }
    if (c === '/' && src[i + 1] === '/') {
      const end = src.indexOf('\n', i);
      const text = src.slice(i, end === -1 ? src.length : end).replace(/\r$/, '');
      if (text.startsWith('///')) pendingDoc.push(text.slice(3).replace(/^ /, ''));
      i = end === -1 ? src.length : end;
      continue;
    }
    if (/[A-Za-z_]/.test(c)) {
      let j = i + 1;
      while (j < src.length && /[A-Za-z0-9_]/.test(src[j])) j++;
      push('ident', src.slice(i, j));
      i = j;
      continue;
    }
    if (/[0-9]/.test(c)) {
      let j = i + 1;
      while (j < src.length && /[0-9]/.test(src[j])) j++;
      push('int', Number(src.slice(i, j)));
      i = j;
      continue;
    }
    if (c === '"') {
      const j = src.indexOf('"', i + 1);
      if (j === -1) throw new Error(`${file}:${line}: unterminated string`);
      push('string', src.slice(i + 1, j));
      i = j + 1;
      continue;
    }
    if (c === '-' && src[i + 1] === '>') { push('punct', '->'); i += 2; continue; }
    if ('{}[]();:=?,.'.includes(c)) { push('punct', c); i++; continue; }
    throw new Error(`${file}:${line}: unexpected character '${c}'`);
  }
  toks.push({ type: 'eof', value: null, line, file, doc: [] });
  return toks;
}

// ─────────────────────────────────────────────────────────────────────────────
// Parser
// ─────────────────────────────────────────────────────────────────────────────

const SCALARS = new Set(['bool', 'i32', 'u32', 'i64', 'u64', 'f32', 'f64', 'string', 'bytes']);

function parse(files) {
  const model = {
    version: null,
    aliases: new Map(),
    enums: new Map(),
    structs: new Map(),
    unions: new Map(),
    commands: [],
    queries: [],
    events: [],
    order: [],
  };
  for (const { name, src } of files) {
    const toks = lex(src, name);
    let p = 0;
    let family = 'General';
    const peek = () => toks[p];
    const next = () => toks[p++];
    const where = (t) => `${t.file}:${t.line}`;
    const expect = (type, value) => {
      const t = next();
      if (t.type !== type || (value !== undefined && t.value !== value)) {
        throw new Error(`${where(t)}: expected ${value ?? type}, got ${t.value ?? t.type}`);
      }
      return t;
    };
    const accept = (type, value) => {
      const t = peek();
      if (t.type === type && (value === undefined || t.value === value)) { p++; return t; }
      return null;
    };
    const parseType = () => {
      const t = expect('ident');
      let list = false;
      if (accept('punct', '[')) { expect('punct', ']'); list = true; }
      return { name: t.value, list };
    };
    const parseFields = (owner) => {
      const fields = [];
      expect('punct', '{');
      while (!accept('punct', '}')) {
        const nameTok = expect('ident');
        const optional = !!accept('punct', '?');
        expect('punct', ':');
        const type = parseType();
        expect('punct', '=');
        const num = expect('int').value;
        expect('punct', ';');
        fields.push({ name: nameTok.value, optional, type, num, doc: nameTok.doc, where: where(nameTok) });
      }
      checkNums(fields, owner);
      return fields;
    };
    const parseAttrs = () => {
      const attrs = new Set();
      if (accept('punct', '[')) {
        do { attrs.add(expect('ident').value); } while (accept('punct', ','));
        expect('punct', ']');
      }
      return attrs;
    };
    while (peek().type !== 'eof') {
      const kw = expect('ident');
      const doc = kw.doc;
      switch (kw.value) {
        case 'version': {
          const major = expect('int').value;
          expect('punct', '.');
          const minor = expect('int').value;
          expect('punct', ';');
          if (model.version) throw new Error(`${where(kw)}: version declared twice`);
          model.version = { major, minor };
          break;
        }
        case 'family': {
          family = expect('string').value;
          expect('punct', ';');
          break;
        }
        case 'alias': {
          const n = expect('ident').value;
          expect('punct', '=');
          const target = expect('ident').value;
          expect('punct', ';');
          if (!SCALARS.has(target)) throw new Error(`${where(kw)}: alias ${n} must name a scalar`);
          define(model, n, where(kw));
          model.aliases.set(n, { name: n, target, doc });
          break;
        }
        case 'enum': {
          const n = expect('ident').value;
          define(model, n, where(kw));
          expect('punct', '{');
          const members = [];
          while (!accept('punct', '}')) {
            const t = next();
            if (t.type !== 'ident' && t.type !== 'string') throw new Error(`${where(t)}: enum member expected`);
            expect('punct', '=');
            const num = expect('int').value;
            expect('punct', ';');
            members.push({ name: t.value, num, doc: t.doc });
          }
          checkNums(members, n);
          if (!members.some((m) => m.num === 0)) throw new Error(`${where(kw)}: enum ${n} needs a member = 0 (the default)`);
          model.enums.set(n, { name: n, members, doc, family });
          model.order.push({ kind: 'enum', name: n });
          break;
        }
        case 'struct': {
          const n = expect('ident').value;
          define(model, n, where(kw));
          const fields = parseFields(n);
          model.structs.set(n, { name: n, fields, doc, family });
          model.order.push({ kind: 'struct', name: n });
          break;
        }
        case 'union': {
          const n = expect('ident').value;
          define(model, n, where(kw));
          const flat = !!accept('ident', 'flat');
          expect('punct', '{');
          const variants = [];
          while (!accept('punct', '}')) {
            const vt = expect('ident');
            expect('punct', ':');
            const type = expect('ident').value;
            expect('punct', '=');
            const num = expect('int').value;
            expect('punct', ';');
            variants.push({ name: vt.value, type, num, doc: vt.doc });
          }
          checkNums(variants, n);
          model.unions.set(n, { name: n, variants, flat, doc, family });
          model.order.push({ kind: 'union', name: n });
          break;
        }
        case 'command':
        case 'query':
        case 'event': {
          const nameTok = expect('ident');
          const n = nameTok.value;
          expect('punct', '=');
          const id = expect('int').value;
          const attrs = parseAttrs();
          const fields = parseFields(n);
          let result = null;
          if (accept('punct', '->')) result = expect('ident').value;
          accept('punct', ';');
          const typeName = kw.value === 'event' ? `${pascal(n)}Event` : pascal(n);
          define(model, typeName, where(kw));
          model.structs.set(typeName, { name: typeName, fields, doc, family, synthetic: kw.value });
          model.order.push({ kind: 'struct', name: typeName });
          const entry = { name: n, typeName, id, attrs, result, doc, family, where: where(kw) };
          if (kw.value === 'command') model.commands.push(entry);
          else if (kw.value === 'query') {
            if (!result) throw new Error(`${where(kw)}: query ${n} needs '-> ResultType'`);
            model.queries.push(entry);
          } else model.events.push(entry);
          break;
        }
        default:
          throw new Error(`${where(kw)}: unknown declaration '${kw.value}'`);
      }
    }
  }
  if (!model.version) throw new Error('schema: no `version major.minor;` declaration');
  synthesize(model);
  validate(model);
  return model;
}

function define(model, n, at) {
  if (model.aliases.has(n) || model.enums.has(n) || model.structs.has(n) || model.unions.has(n) || SCALARS.has(n)) {
    throw new Error(`${at}: '${n}' is already defined`);
  }
}

function checkNums(items, owner) {
  const seenNum = new Map();
  const seenName = new Set();
  for (const it of items) {
    if (seenNum.has(it.num)) throw new Error(`${owner}: number ${it.num} used by both ${seenNum.get(it.num)} and ${it.name}`);
    if (seenName.has(it.name)) throw new Error(`${owner}: duplicate name ${it.name}`);
    seenNum.set(it.num, it.name);
    seenName.add(it.name);
  }
}

/** The four top-level unions are derived from the command/query/event declarations. */
function synthesize(model) {
  const EMPTY = 'Empty';
  if (!model.structs.has(EMPTY)) throw new Error('schema: struct Empty {} must be declared');
  const mk = (name, entries, typeOf, doc) => {
    if (model.unions.has(name)) throw new Error(`schema: ${name} is synthesized; do not declare it`);
    model.unions.set(name, {
      name,
      flat: true,
      doc,
      family: 'Envelope',
      synthetic: true,
      variants: entries.map((e) => ({ name: e.name, type: typeOf(e), num: e.id, doc: e.doc })),
    });
    checkNums(model.unions.get(name).variants, name);
    model.order.push({ kind: 'union', name });
  };
  mk('Command', model.commands, (e) => e.typeName, ['Every command, keyed by its schema id.']);
  mk('CommandResult', model.commands, (e) => e.result ?? EMPTY, ['The typed result of a successful command; same key as its command.']);
  mk('Query', model.queries, (e) => e.typeName, ['Every query, keyed by its schema id.']);
  mk('QueryResult', model.queries, (e) => e.result, ['The typed result of a query; same key as its query.']);
  mk('Event', model.events, (e) => e.typeName, ['Every change / status event, keyed by its schema id.']);
}

function validate(model) {
  const known = (n) => SCALARS.has(n) || model.aliases.has(n) || model.enums.has(n) || model.structs.has(n) || model.unions.has(n);
  for (const s of model.structs.values()) {
    for (const f of s.fields) {
      if (!known(f.type.name)) throw new Error(`${f.where}: unknown type ${f.type.name}`);
      if (f.optional && f.type.list) throw new Error(`${f.where}: a list cannot be optional (an empty list is absent)`);
      if (f.num < 1 || f.num > 536870911) throw new Error(`${f.where}: field number out of range`);
    }
  }
  for (const u of model.unions.values()) {
    for (const v of u.variants) {
      if (v.type !== 'void' && !known(v.type)) throw new Error(`union ${u.name}.${v.name}: unknown type ${v.type}`);
      if (u.flat && !model.structs.has(v.type)) throw new Error(`flat union ${u.name}.${v.name} must carry a struct`);
      if (u.flat && model.structs.get(v.type).fields.some((f) => f.name === 'type')) {
        throw new Error(`flat union ${u.name}: struct ${v.type} may not have a field named 'type'`);
      }
      if (v.num < 1) throw new Error(`union ${u.name}.${v.name}: variant number must be ≥ 1`);
    }
  }
  for (const c of model.commands) {
    for (const a of c.attrs) if (!['control', 'io', 'coalesce'].includes(a)) throw new Error(`${c.where}: unknown attribute ${a}`);
    if (c.result && !model.structs.has(c.result)) throw new Error(`${c.where}: result ${c.result} must be a struct`);
  }
  for (const q of model.queries) {
    if (q.attrs.size) throw new Error(`${q.where}: queries take no attributes`);
    if (!model.structs.has(q.result)) throw new Error(`${q.where}: result ${q.result} must be a struct`);
  }
  for (const e of model.events) {
    for (const a of e.attrs) if (a !== 'ephemeral') throw new Error(`${e.where}: unknown attribute ${a}`);
  }
}

